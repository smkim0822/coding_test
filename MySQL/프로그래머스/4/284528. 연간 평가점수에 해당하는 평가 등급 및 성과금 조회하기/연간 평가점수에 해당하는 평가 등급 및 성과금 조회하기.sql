WITH EMP_SCORE AS (
    SELECT
        EMP_NO,
        AVG(SCORE) AS AVG_SCORE
    FROM HR_GRADE
    GROUP BY EMP_NO
)
SELECT 
    E.EMP_NO,
    E.EMP_NAME,
    CASE
        WHEN S.AVG_SCORE >= 96 THEN 'S'
        WHEN S.AVG_SCORE >= 90 THEN 'A'
        WHEN S.AVG_SCORE >= 80 THEN 'B'
        ELSE 'C'
    END AS GRADE,
    CASE
        WHEN S.AVG_SCORE >= 96 THEN E.SAL * 0.20
        WHEN S.AVG_SCORE >= 90 THEN E.SAL * 0.15
        WHEN S.AVG_SCORE >= 80 THEN E.SAL * 0.10
        ELSE 0
    END AS BONUS
FROM HR_EMPLOYEES E
JOIN EMP_SCORE S ON E.EMP_NO = S.EMP_NO
ORDER BY E.EMP_NO ASC;